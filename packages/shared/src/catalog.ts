export function findActivityDefinition(id: string): ActivityDefinition | undefined {
  return ACTIVITY_CATALOG.find((a) => a.id === id);
}

export function activityRequestFromDefinition(def: ActivityDefinition): ActivityRequest {
  return {
    id: def.id,
    label: def.label,
    emoji: def.emoji,
    query: def.query,
    ...(def.includedType ? { includedType: def.includedType } : {}),
    durationMinutes: def.durationMinutes,
    minDurationMinutes: def.minDurationMinutes,
    frequency: def.defaultFrequency,
    priority: 'normal',
    outdoor: def.outdoor,
  };
}
